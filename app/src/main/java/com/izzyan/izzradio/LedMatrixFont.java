    private static void add(char character, String pattern) {
        String[] lines=pattern.split("/");
        if(lines.length!=HEIGHT) throw new IllegalArgumentException("Bad LED height for "+character);
        int[] rows=new int[HEIGHT];
        for(int row=0;row<HEIGHT;row++) {
            if(lines[row].length()!=WIDTH) throw new IllegalArgumentException("Bad LED width for "+character);
            rows[row]=Integer.parseInt(lines[row],2);
        }
        GLYPHS.put(character,rows);
    }

    static int[] rows(char value) {
        int[] bits=GLYPHS.get(Character.toUpperCase(value));
        return bits!=null?bits:GLYPHS.get('?');
    }

    /** Normalize common accented Malay/Latin text and Unicode punctuation; never emit broken glyphs. */
    static String normalize(String input) {
        if(input==null || input.isEmpty()) return "";
        StringBuilder result=new StringBuilder();
        for(int offset=0;offset<input.length();) {
            int point=input.codePointAt(offset);
            offset+=Character.charCount(point);
            if(point=='\u2014'||point=='\u2013'||point=='\u2010'||point=='\u2212') point='-';
            if(point=='\u2018'||point=='\u2019'||point=='\u02bc') point='\'';
            if(point=='\u2026') { result.append("..."); continue; }
            if(point=='\u2022'||point=='\u00b7') point=' ';
            if(Character.isWhitespace(point)) { result.append(' '); continue; }
            if(point=='\u266a'||point=='\u266b') continue;
            String decomposed=Normalizer.normalize(new String(Character.toChars(point)),Normalizer.Form.NFD);
            int ascii=-1;
            for(int i=0;i<decomposed.length();i++) {
                int candidate=decomposed.codePointAt(i);
                if(Character.getType(candidate)==Character.NON_SPACING_MARK) continue;
                ascii=candidate;
                break;
            }
            if(ascii<0) continue;
            if(ascii=='\u00df') { result.append("SS"); continue; }
            char upper=(char)Character.toUpperCase(ascii);
            result.append(GLYPHS.containsKey(upper)?upper:'?');
        }
        return result.toString();
    }

